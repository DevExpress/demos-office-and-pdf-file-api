using DevExpress.XtraRichEdit;
using DevExpress.XtraRichEdit.API.Native;

class Program {
    static readonly string InputFilePath = Path.Combine("Documents", "Sample.docx");
    const string OutputFileName = "CompareDocuments_Result.docx";
    static readonly DocumentFormat OutputFormat = DocumentFormat.Docx;

    static int Main() {
        try {
            var inputPath = Path.Combine(AppContext.BaseDirectory, InputFilePath);
            var outputPath = Path.Combine(AppContext.BaseDirectory, OutputFileName);
            using var originalStream = File.OpenRead(inputPath);
            using var revisedStream = CreateRevisedDocument(inputPath);
            using var outputStream = CompareDocuments(originalStream, revisedStream, OutputFormat);
            using var fileStream = File.Create(outputPath);
            outputStream.CopyTo(fileStream);
            Console.WriteLine($"Created {outputPath}");
            return 0;
        }
        catch(Exception exception) {
            Console.Error.WriteLine(exception);
            return 1;
        }
    }

    static Stream CreateRevisedDocument(string inputPath) {
        using var wordProcessor = new RichEditDocumentServer();
        wordProcessor.LoadDocument(inputPath);
        var document = wordProcessor.Document;
        document.AppendText("\nRevised copy generated by the console sample.");

        var revisedStream = new MemoryStream();
        wordProcessor.SaveDocument(revisedStream, DocumentFormat.Docx);
        revisedStream.Position = 0;
        return revisedStream;
    }

    static Stream CompareDocuments(Stream originalStream, Stream revisedStream, DocumentFormat outputFormat) {
        using var originalWordProcessor = new RichEditDocumentServer();
        using var revisedWordProcessor = new RichEditDocumentServer();
        originalWordProcessor.LoadDocument(originalStream);
        revisedWordProcessor.LoadDocument(revisedStream);

        var options = new CompareDocumentOptions {
            CompareFormatting = true,
            CompareCaseChanges = true,
            CompareHeadersAndFooters = true,
            CompareTextBoxes = true,
            ComparisonLevel = ComparisonLevel.Word,
            Author = "Test Author",
            DateTime = DateTime.Now
        };

        var comparedDocument = originalWordProcessor.Document.Compare(revisedWordProcessor.Document, options);
        var outputStream = new MemoryStream();
        comparedDocument.SaveDocument(outputStream, outputFormat);
        outputStream.Position = 0;
        return outputStream;
    }
}
